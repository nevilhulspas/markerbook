/**
 * Write the migration that loads src/lib/units/data/loinc-molar-masses.json
 * into the database and keeps biomarkers.molar_mass in step with loinc_code.
 *
 *   npx tsx scripts/units/gen-molar-mass-migration.ts <version, e.g. 20261019210000>
 *
 * Rerun build-molar-masses.ts first after a new LOINC release, then generate a
 * new migration version: the SQL is idempotent and replaces the reference rows.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const version = process.argv[2]
if (!/^\d{14}$/.test(version ?? '')) throw new Error('usage: gen-molar-mass-migration.ts <14-digit version>')

interface Analyte {
  name: string
  molarMass: number
  valence?: number
  source: string
  massUnit?: string
  molarUnit?: string
}
const data = JSON.parse(
  readFileSync(join(__dirname, '..', '..', 'src', 'lib', 'units', 'data', 'loinc-molar-masses.json'), 'utf8')
) as { source: string; analytes: Record<string, Analyte>; codes: Record<string, string> }

const q = (v: string | null | undefined) => (v == null || v === '' ? 'NULL' : `'${v.replace(/'/g, "''")}'`)

const analyteRows = Object.entries(data.analytes)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([part, a]) => `  (${q(part)}, ${q(a.name)}, ${a.molarMass}, ${a.valence ?? 'NULL'}, ${q(a.massUnit)}, ${q(a.molarUnit)}, ${q(a.source)})`)
const codeRows = Object.entries(data.codes)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([code, part]) => `  (${q(code)}, ${q(part)})`)

export const FILL_BIOMARKERS_SQL = `UPDATE public.biomarkers b
SET molar_mass = a.molar_mass,
    valence = a.valence,
    typical_mass_unit = a.mass_unit,
    typical_molar_unit = a.molar_unit
FROM public.loinc_analyte_codes c
JOIN public.loinc_analytes a ON a.part_number = c.part_number
WHERE c.loinc_code = b.loinc_code
  AND (b.molar_mass IS DISTINCT FROM a.molar_mass
    OR b.valence IS DISTINCT FROM a.valence
    OR b.typical_mass_unit IS DISTINCT FROM a.mass_unit
    OR b.typical_molar_unit IS DISTINCT FROM a.molar_unit);`

const sql = `-- Molar masses for every LOINC mass / molar concentration code, so a result
-- in any mass unit (ng/mL, mg/dL, …) converts to any molar unit (nmol/L,
-- mmol/L, …) and, for ions, to mEq/L. Generated by
-- scripts/units/gen-molar-mass-migration.ts from ${data.source}.
-- LOINC® is a registered trademark of Regenstrief Institute, Inc.
--
-- biomarkers.molar_mass / valence / typical_*_unit follow loinc_code through a
-- trigger, so markers captured later from LOINC convert too. Idempotent.

CREATE TABLE IF NOT EXISTS public.loinc_analytes (
  part_number text PRIMARY KEY,
  name text NOT NULL,
  molar_mass numeric NOT NULL CHECK (molar_mass > 0),
  valence smallint CHECK (valence > 0),
  mass_unit text,
  molar_unit text,
  source text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.loinc_analyte_codes (
  loinc_code text PRIMARY KEY,
  part_number text NOT NULL REFERENCES public.loinc_analytes(part_number) ON DELETE CASCADE
);

ALTER TABLE public.loinc_analytes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.loinc_analyte_codes ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "LOINC analytes readable by authenticated" ON public.loinc_analytes;
CREATE POLICY "LOINC analytes readable by authenticated" ON public.loinc_analytes FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "LOINC analyte codes readable by authenticated" ON public.loinc_analyte_codes;
CREATE POLICY "LOINC analyte codes readable by authenticated" ON public.loinc_analyte_codes FOR SELECT TO authenticated USING (true);

-- Replace the reference data with this release.
DELETE FROM public.loinc_analyte_codes;
DELETE FROM public.loinc_analytes;

INSERT INTO public.loinc_analytes (part_number, name, molar_mass, valence, mass_unit, molar_unit, source) VALUES
${analyteRows.join(',\n')};

INSERT INTO public.loinc_analyte_codes (loinc_code, part_number) VALUES
${codeRows.join(',\n')};

ALTER TABLE public.biomarkers
  ADD COLUMN IF NOT EXISTS molar_mass numeric,
  ADD COLUMN IF NOT EXISTS valence smallint,
  ADD COLUMN IF NOT EXISTS typical_mass_unit text,
  ADD COLUMN IF NOT EXISTS typical_molar_unit text;

COMMENT ON COLUMN public.biomarkers.molar_mass IS 'g/mol, from loinc_analytes via loinc_code; used for mass <-> molar unit conversion';
COMMENT ON COLUMN public.biomarkers.valence IS 'charge number, for mEq/L <-> mmol/L';

CREATE OR REPLACE FUNCTION public.fill_biomarker_molar_mass()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'INSERT' OR NEW.loinc_code IS DISTINCT FROM OLD.loinc_code THEN
    SELECT a.molar_mass, a.valence, a.mass_unit, a.molar_unit
      INTO NEW.molar_mass, NEW.valence, NEW.typical_mass_unit, NEW.typical_molar_unit
    FROM public.loinc_analyte_codes c
    JOIN public.loinc_analytes a ON a.part_number = c.part_number
    WHERE c.loinc_code = NEW.loinc_code;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS biomarkers_fill_molar_mass ON public.biomarkers;
CREATE TRIGGER biomarkers_fill_molar_mass
  BEFORE INSERT OR UPDATE OF loinc_code ON public.biomarkers
  FOR EACH ROW EXECUTE FUNCTION public.fill_biomarker_molar_mass();

${FILL_BIOMARKERS_SQL}
`

const out = join(__dirname, '..', '..', 'supabase', 'migrations', `${version}_loinc_molar_masses.sql`)
writeFileSync(out, sql)
console.log(`wrote ${out} (${analyteRows.length} substances, ${codeRows.length} codes, ${(sql.length / 1024).toFixed(0)} KB)`)
