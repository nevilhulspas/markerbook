'use client'

import { useSyncExternalStore } from 'react'
import { AlertTriangle } from 'lucide-react'

import { Button } from '@/components/ui/button'
import {
  Tooltip,
  TooltipContent,
  TooltipProvider,
  TooltipTrigger,
} from '@/components/ui/tooltip'

const DISCLAIMER_KEY = 'interpretation_disclaimer_seen'

export function FullDisclaimer({ onDismiss }: { onDismiss: () => void }) {
  return (
    <div className="rounded-lg border border-yellow-200 bg-yellow-50 p-4 dark:border-yellow-900/50 dark:bg-yellow-950/30">
      <div className="flex gap-3">
        <AlertTriangle className="mt-0.5 size-5 shrink-0 text-yellow-600 dark:text-yellow-500" />
        <div className="space-y-2">
          <p className="text-sm font-medium text-yellow-800 dark:text-yellow-200">
            AI-Generated Health Information
          </p>
          <p className="text-sm text-yellow-700 dark:text-yellow-300">
            This interpretation is generated by AI and is for informational
            purposes only. It is not medical advice and should not replace
            professional consultation with your healthcare provider. Always
            discuss your results with a qualified medical professional.
          </p>
          <Button
            size="sm"
            variant="outline"
            onClick={() => {
              localStorage.setItem(DISCLAIMER_KEY, 'true')
              onDismiss()
            }}
          >
            I understand
          </Button>
        </div>
      </div>
    </div>
  )
}

const noopSubscribe = () => () => {}

export function useDisclaimerSeen(): boolean {
  return useSyncExternalStore(
    noopSubscribe,
    () => localStorage.getItem(DISCLAIMER_KEY) === 'true',
    () => true // server + hydration: assume seen to avoid a flash
  )
}

export function CompactDisclaimer() {
  return (
    <TooltipProvider>
      <Tooltip>
        <TooltipTrigger asChild>
          <span className="inline-flex cursor-help items-center gap-1 text-xs text-muted-foreground">
            <AlertTriangle className="size-3" />
            Not medical advice
          </span>
        </TooltipTrigger>
        <TooltipContent side="top" className="max-w-xs">
          <p>
            This AI interpretation is for informational purposes only and should
            not replace professional medical advice.
          </p>
        </TooltipContent>
      </Tooltip>
    </TooltipProvider>
  )
}
